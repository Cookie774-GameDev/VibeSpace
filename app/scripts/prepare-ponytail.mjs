#!/usr/bin/env node

import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';

import {
  PONYTAIL_PIN,
  sha256Normalized,
  verifyPonytailUpstream,
} from './verify-ponytail-upstream.mjs';

const scriptPath = fileURLToPath(import.meta.url);
const defaultRepoRoot = path.resolve(path.dirname(scriptPath), '..', '..');

const SOURCE_ARTIFACTS = [
  { path: 'skills/ponytail/SKILL.md', hashKey: 'upstreamSkill' },
  { path: 'skills/ponytail-audit/SKILL.md', hashKey: 'upstreamAudit' },
  { path: 'LICENSE', hashKey: 'upstreamLicense' },
  { path: 'hooks/ponytail-instructions.js', hashKey: 'upstreamBuilder' },
  { path: 'hooks/ponytail-config.js', hashKey: 'upstreamBuilderConfig' },
  { path: 'package.json', hashKey: 'upstreamPackage' },
  { path: 'UPSTREAM.md', hashKey: 'vendorProvenance' },
];

const defaultIo = Object.freeze({
  exists: existsSync,
  readFile: readFileSync,
  writeFile: writeFileSync,
  mkdir: mkdirSync,
});

function runPinnedBuilder(upstreamRoot) {
  const requireFromUpstream = createRequire(path.join(upstreamRoot, 'package.json'));
  const builderPath = path.join(upstreamRoot, 'hooks', 'ponytail-instructions.js');
  const builder = requireFromUpstream(builderPath);
  if (typeof builder.getPonytailInstructions !== 'function') {
    throw new Error('Pinned upstream builder does not export getPonytailInstructions().');
  }
  return builder.getPonytailInstructions('full');
}

export function createPonytailArtifact({
  upstreamRoot,
  pin = PONYTAIL_PIN,
  readFile = readFileSync,
  runBuilder = runPinnedBuilder,
} = {}) {
  if (typeof upstreamRoot !== 'string' || !upstreamRoot) {
    throw new Error('A verified Ponytail upstream root is required.');
  }

  const source = new Map();
  for (const artifact of SOURCE_ARTIFACTS) {
    const bytes = readFile(path.join(upstreamRoot, artifact.path));
    const actualHash = sha256Normalized(bytes);
    const expectedHash = pin.hashes[artifact.hashKey];
    if (actualHash !== expectedHash) {
      throw new Error(
        `Pinned upstream hash mismatch for ${artifact.path}: expected ${expectedHash}, received ${actualHash}.`,
      );
    }
    source.set(artifact.path, Buffer.from(bytes).toString('utf8').replace(/\r\n?/gu, '\n'));
  }

  const provenance = source.get('UPSTREAM.md');
  const provenanceFacts = [
    pin.repository,
    pin.release,
    pin.commit,
    `skills/ponytail/SKILL.md SHA-256: ${pin.hashes.upstreamSkill}`,
    `skills/ponytail-audit/SKILL.md SHA-256: ${pin.hashes.upstreamAudit}`,
  ];
  if (!provenanceFacts.every((fact) => provenance.includes(fact))) {
    throw new Error('Vendored Ponytail provenance facts do not match the pinned release.');
  }

  let packageMetadata;
  try {
    packageMetadata = JSON.parse(source.get('package.json'));
  } catch (error) {
    throw new Error(`Pinned Ponytail package metadata is invalid: ${error.message}`);
  }

  const fullInstructions = runBuilder(upstreamRoot);
  const fullInstructionsHash = sha256Normalized(fullInstructions);
  if (fullInstructionsHash !== pin.hashes.generatedInstructions) {
    throw new Error(
      `Pinned full-mode builder output hash mismatch: expected ${pin.hashes.generatedInstructions}, received ${fullInstructionsHash}.`,
    );
  }

  const ponytailRaw = source.get('skills/ponytail/SKILL.md');
  const auditRaw = source.get('skills/ponytail-audit/SKILL.md');
  return {
    source: {
      repository: pin.repository,
      release: pin.release,
      commit: pin.commit,
    },
    package: {
      name: packageMetadata.name,
      version: packageMetadata.version,
      license: packageMetadata.license,
    },
    instructions: {
      full: fullInstructions,
      sha256: fullInstructionsHash,
    },
    skills: {
      ponytail: {
        path: 'skills/ponytail/SKILL.md',
        raw: ponytailRaw,
        sha256: pin.hashes.upstreamSkill,
      },
      audit: {
        path: 'skills/ponytail-audit/SKILL.md',
        raw: auditRaw,
        sha256: pin.hashes.upstreamAudit,
      },
    },
    hashes: {
      license: pin.hashes.upstreamLicense,
      builder: pin.hashes.upstreamBuilder,
      builderConfig: pin.hashes.upstreamBuilderConfig,
      package: pin.hashes.upstreamPackage,
      provenance: pin.hashes.vendorProvenance,
    },
  };
}

export async function renderPonytailModule(artifact, filepath) {
  const targetPath =
    filepath ?? path.join(defaultRepoRoot, 'app', 'src', 'lib', 'ai', 'ponytail.generated.ts');
  const source = [
    '// Generated by `node app/scripts/prepare-ponytail.mjs`; do not edit by hand.',
    `export const ponytailArtifact = Object.freeze(${JSON.stringify(artifact, null, 2)} as const);`,
    '',
  ].join('\n');
  const config = (await resolveConfig(targetPath)) ?? {};
  return format(source, { ...config, filepath: targetPath });
}

export function writePonytailModule({
  target,
  expectedContents,
  checkOnly = false,
  io = defaultIo,
} = {}) {
  if (checkOnly) {
    if (!io.exists(target)) {
      throw new Error(
        `Generated Ponytail artifact is missing: ${target}. Run prepare-ponytail.mjs.`,
      );
    }
    const actualContents = io.readFile(target, 'utf8');
    if (actualContents !== expectedContents) {
      throw new Error(`Generated Ponytail artifact is stale: ${target}. Run prepare-ponytail.mjs.`);
    }
    return { status: 'checked', target };
  }

  if (io.exists(target) && io.readFile(target, 'utf8') === expectedContents) {
    return { status: 'unchanged', target };
  }
  io.mkdir(path.dirname(target), { recursive: true });
  io.writeFile(target, expectedContents, 'utf8');
  return { status: 'written', target };
}

export async function preparePonytail({
  repoRoot = defaultRepoRoot,
  upstreamRoot = path.join(repoRoot, 'app', 'third_party', 'ponytail'),
  target = path.join(repoRoot, 'app', 'src', 'lib', 'ai', 'ponytail.generated.ts'),
  pin = PONYTAIL_PIN,
  checkOnly = false,
  verifier = verifyPonytailUpstream,
  io = defaultIo,
  runBuilder = runPinnedBuilder,
} = {}) {
  const verification = verifier({ repoRoot, upstreamRoot });
  if (verification.status !== 'pass') {
    throw new Error(
      `Pinned Ponytail verification failed; generated frontend artifact was not written. ${JSON.stringify(verification.failures)}`,
    );
  }

  const artifact = createPonytailArtifact({
    upstreamRoot,
    pin,
    readFile: io.readFile,
    runBuilder,
  });
  const expectedContents = await renderPonytailModule(artifact, target);
  const result = writePonytailModule({ target, expectedContents, checkOnly, io });
  return {
    ...result,
    source: artifact.source,
    hashes: {
      fullInstructions: artifact.instructions.sha256,
      ponytailSkill: artifact.skills.ponytail.sha256,
      auditSkill: artifact.skills.audit.sha256,
    },
  };
}

const isMain =
  process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  try {
    const result = await preparePonytail({ checkOnly: process.argv.includes('--check') });
    process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
